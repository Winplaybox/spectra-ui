import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { createNativeTheme } from "./native-theme.mjs";
import {
  modes,
  primitives,
  resolvedPacks,
  semantic,
} from "./token-sources.mjs";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const distDir = path.resolve(__dirname, "../dist");

// Ensure output directories exist
fs.mkdirSync(path.join(distDir, "css"), { recursive: true });
fs.mkdirSync(path.join(distDir, "ts"), { recursive: true });
fs.mkdirSync(path.join(distDir, "json"), { recursive: true });

function flattenTokens(values) {
  const result = {};
  for (const [key, value] of Object.entries(values)) {
    const name = key.replaceAll(".", "-");
    result[name] = value;
    if (name.includes("-semantic-")) {
      result[name.replace("-semantic-", "-")] = value;
    }
  }
  return result;
}

const packs = Object.fromEntries(
  Object.entries(resolvedPacks()).map(([pack, values]) => [
    pack,
    Object.fromEntries(
      modes.map((mode) => [mode, flattenTokens(values[mode])]),
    ),
  ]),
);
const { light: lightFlat, dark: darkFlat } = packs.minimal;
const nativeThemes = Object.fromEntries(
  Object.entries(packs).map(([pack, values]) => [
    pack,
    Object.fromEntries(
      modes.map((mode) => [mode, createNativeTheme(values[mode], primitives)]),
    ),
  ]),
);

// Format CSS variable block
function generateCssBlock(selector, flatTokens) {
  const lines = [`${selector} {`];
  for (const [key, val] of Object.entries(flatTokens)) {
    const varName = `--${key}`;
    const spectraVarName = `--spectra-${key}`;
    lines.push(`  ${varName}: ${val};`);
    lines.push(`  ${spectraVarName}: ${val};`);
  }
  lines.push("}\n");
  return lines.join("\n");
}

// Generate CSS (Phase 1: Minimal Flat Style, Light & Dark dynamic modes)
let cssOutput = `/**
 * Spectra UI — Compiled Design Tokens (Phase 1: Minimal Flat Style)
 * Automatically generated by @winplaybox/tokens build engine. Do not edit manually.
 */\n\n`;

cssOutput += generateCssBlock(
  ':root, [data-pack="minimal"], [data-mode="light"], [data-pack="minimal"][data-mode="light"]',
  lightFlat,
);
cssOutput += generateCssBlock(
  '[data-mode="dark"], [data-pack="minimal"][data-mode="dark"]',
  darkFlat,
);
for (const mode of modes) {
  cssOutput += generateCssBlock(`[data-pack="base"][data-mode="${mode}"]`, {
    ...packs.base[mode],
    "font-primitive-family-sans": "var(--fontFamily-body)",
    "font-family-sans": "var(--fontFamily-body)",
  });
}

fs.writeFileSync(path.join(distDir, "css/tokens.css"), cssOutput, "utf8");

// Generate JSON
const jsonOutput = {
  pack: "minimal",
  modes: {
    light: lightFlat,
    dark: darkFlat,
  },
  primitives,
  semantic,
};
fs.writeFileSync(
  path.join(distDir, "json/tokens.json"),
  JSON.stringify(
    {
      ...jsonOutput,
      packs: { base: packs.base },
    },
    null,
    2,
  ),
  "utf8",
);

const sharedTypes = `
export type ColorScheme = 'light' | 'dark';
export type StylePack = 'minimal' | 'base';

type FontRole = 'display' | 'heading' | 'subheading' | 'paragraph' | 'label' | 'caption';
type SpacingSize = 'xs' | 'sm' | 'md' | 'lg' | 'xl';
interface NativeTextStyle {
  fontSize: number;
  lineHeight: number;
  fontWeight: '400' | '500' | '600' | '700' | '800';
  fontFamily?: string;
  letterSpacing?: number;
}
interface NativeShadow {
  boxShadow?: string;
  ios?: {
    shadowColor: string;
    shadowOffset: { width: number; height: number };
    shadowRadius: number;
    shadowOpacity: number;
  };
  android: { elevation: number };
}
export interface NativeTheme {
  colors: Record<
    | 'canvas' | 'surface' | 'surfaceAlt' | 'text' | 'textMuted' | 'border' | 'borderStrong'
    | 'primary' | 'onPrimary' | 'accent' | 'accentBackground' | 'success' | 'successBackground'
    | 'error' | 'errorBackground' | 'warning' | 'warningBackground',
    string
  >;
  spacing: {
    padding: Record<SpacingSize, number>;
    gap: Record<SpacingSize, number>;
    gutter: number;
    margin: Record<Exclude<SpacingSize, 'xl'>, number>;
  };
  radii: Record<'none' | 'sm' | 'md' | 'lg' | 'control' | 'full', number>;
  typography: Record<FontRole, NativeTextStyle>;
  shadows: Record<'raised' | 'overlay', NativeShadow>;
  focusRing?: { boxShadow: string };
  motion: Record<'instant' | 'subtle' | 'emphasis' | 'sheet', number>;
}
`;

function generateModule(typed) {
  const literal = (value) =>
    JSON.stringify(value, null, 2) + (typed ? " as const" : "");
  const parameters = typed
    ? "mode: ColorScheme = 'light', pack: StylePack = 'minimal'"
    : "mode = 'light', pack = 'minimal'";
  return `/**
 * Spectra UI — Design Tokens
 */
${typed ? sharedTypes + "\nexport type TokenKey = keyof typeof lightTokens;\n" : ""}
export const tokens = ${literal(jsonOutput)};

export const lightTokens = ${literal(lightFlat)};
export const darkTokens = ${literal(darkFlat)};
const baseModes = ${literal(packs.base)};
const nativeThemes = ${literal(nativeThemes)};

export function getTokens(${parameters})${typed ? ": Record<string, string>" : ""} {
  if (pack === 'base') return mode === 'dark' ? baseModes.dark : baseModes.light;
  return mode === 'dark' ? darkTokens : lightTokens;
}

export function getNativeTheme(${parameters})${typed ? ": NativeTheme" : ""} {
  return nativeThemes[pack][mode];
}
`;
}

fs.writeFileSync(
  path.join(distDir, "ts/tokens.js"),
  generateModule(false),
  "utf8",
);
fs.writeFileSync(
  path.join(distDir, "ts/tokens.ts"),
  generateModule(true),
  "utf8",
);

const indexJs = `export * from './tokens.js';\n`;
fs.writeFileSync(path.join(distDir, "ts/index.js"), indexJs, "utf8");

const indexTs = `export * from './tokens';\n`;
fs.writeFileSync(path.join(distDir, "ts/index.ts"), indexTs, "utf8");

const dtsOutput = `${sharedTypes}
export type TokenKey = string;

export declare const tokens: {
  pack: 'minimal';
  modes: {
    light: Record<string, string>;
    dark: Record<string, string>;
  };
};

export declare const lightTokens: Record<string, string>;
export declare const darkTokens: Record<string, string>;

export declare function getTokens(mode?: ColorScheme, pack?: StylePack): Record<string, string>;
export declare function getNativeTheme(mode?: ColorScheme, pack?: StylePack): NativeTheme;
`;
fs.writeFileSync(path.join(distDir, "ts/tokens.d.ts"), dtsOutput, "utf8");
fs.writeFileSync(path.join(distDir, "ts/index.d.ts"), dtsOutput, "utf8");

console.log(
  "✅ Tokens compiled successfully to dist/css, dist/ts, and dist/json",
);
